export function translate(language, key) {
  return translations[language]?.[key] ?? translations.de[key] ?? key;
}

export function applyTranslations(root, language) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(language, element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute(
      "aria-label",
      translate(language, element.dataset.i18nAriaLabel),
    );
  });
  root.querySelectorAll("[data-i18n-content]").forEach((element) => {
    element.setAttribute(
      "content",
      translate(language, element.dataset.i18nContent),
    );
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute(
      "placeholder",
      translate(language, element.dataset.i18nPlaceholder),
    );
  });
}
